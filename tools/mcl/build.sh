#!/usr/bin/env bash
#
# Build MCL 22-282 with its cimfomfa/libtingea dependency.
#
# MCL's configure expects libtingea to be installed. cimfomfa's release
# tarball has no generated configure script, so CYAN builds its small C
# library directly, installs the headers/library into the build prefix, and
# then runs MCL's configure. Only the `mcl` executable is built; the optional
# mcx* utilities and RCL scripts are not needed by OrthoFinder or YR-MPE.

set -euo pipefail

TOOL_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=../../scripts/common.sh
source "$TOOL_DIR/../../scripts/common.sh"

tool=mcl
version="$(tr -d '[:space:]' < "$TOOL_DIR/VERSION")"
build="$CYAN_BUILD/$tool"
work="$build/src"
stage="$CYAN_BUILD/stage/$tool"
prefix="$build/prefix"

rm -rf "$build"
mkdir -p "$work" "$stage" "$prefix/lib" "$prefix/include/tingea"
cp -a "$TOOL_DIR/src"/. "$work"/

patch_file="$build/mcl-mingw.patch"
tr -d '\r' < "$TOOL_DIR/patches/mcl-mingw.patch" > "$patch_file"
while IFS= read -r header; do
  file="${header#+++ b/}"
  file="${file%%$'\t'*}"
  [[ -f "$work/$file" ]] || continue
  tr -d '\r' < "$work/$file" > "$work/$file.cyan-tmp"
  mv "$work/$file.cyan-tmp" "$work/$file"
done < <(grep '^+++ b/' "$patch_file")
patch -p1 -d "$work" --batch < "$patch_file"

# cimfomfa's checks are normally generated by its configure script.
cat > "$work/cimfomfa/config.h" <<'EOF'
#define HAVE_UNISTD_H 1
#define HAVE_VA_COPY 1
#ifndef _WIN32
#define HAVE_GETPAGESIZE 1
#endif
EOF

# MinGW's unistd.h exposes ftruncate through the deprecated inline _chsize,
# and cimfomfa includes its own io.h for the POSIX read()/write() names.
cat > "$work/wincompat.h" <<'EOF'
#ifdef _WIN32
int _read(int, void *, unsigned int);
int _write(int, const void *, unsigned int);
#define read _read
#define write _write
#define getpagesize() 4096
#endif
EOF

cimfomfa_sources=(
  alloc array rand equate opt io err hash heap let list gralloc tok ting ding tr types
)
objects=()
cimfomfa_flags=(-O2 -I"$work/cimfomfa" -I"$work/cimfomfa/tingea")
if [[ "$CYAN_PLATFORM" == windows ]]; then
  cimfomfa_flags+=(-D__CRT__NO_INLINE -include "$work/wincompat.h")
fi
for name in "${cimfomfa_sources[@]}"; do
  obj="$build/cimfomfa-$name.o"
  "$CC" "${cimfomfa_flags[@]}" -c "$work/cimfomfa/tingea/$name.c" -o "$obj"
  objects+=("$obj")
done
"$AR" rcs "$prefix/lib/libtingea.a" "${objects[@]}"
cp "$work"/cimfomfa/tingea/*.h "$prefix/include/tingea/"

mcl_cflags="-O2"
mcl_ldflags="-L$prefix/lib"
if [[ "$CYAN_PLATFORM" == windows ]]; then
  mcl_cflags="$mcl_cflags -D__CRT__NO_INLINE"
fi
if [[ "$CYAN_PLATFORM" != macos ]]; then
  mcl_ldflags="$mcl_ldflags -static"
fi

log "Configuring MCL $version ($CYAN_PLATFORM $CYAN_ARCH)"
(
  cd "$work/mcl"
  ./configure --prefix="$prefix" CC="$CC" \
    CFLAGS="$mcl_cflags" CPPFLAGS="-I$prefix/include" LDFLAGS="$mcl_ldflags"
  make -C src/clew -j "$CYAN_JOBS"
  make -C src/mcl -j "$CYAN_JOBS"
  make -C src/gryphon -j "$CYAN_JOBS"
  make -C src/impala -j "$CYAN_JOBS"
  make -C src/shmcl -j "$CYAN_JOBS" "mcl$CYAN_EXE"
)

bin_path="$work/mcl/src/shmcl/mcl$CYAN_EXE"
[[ -f "$bin_path" ]] || die "MCL binary not found: $bin_path"
cp "$bin_path" "$stage/mcl$CYAN_EXE"
cp "$TOOL_DIR/LICENSE-MCL" "$TOOL_DIR/LICENSE-CIMFOMFA" \
   "$TOOL_DIR/README.md" "$TOOL_DIR/VERSION" "$stage/"
cp "$TOOL_DIR/examples/example.abc" "$stage/"

if [[ "$CYAN_PLATFORM" == macos ]]; then
  "$STRIP" -x "$stage/mcl" 2>/dev/null || true
else
  "$STRIP" --strip-unneeded "$stage/mcl$CYAN_EXE" 2>/dev/null || true
fi

cat > "$stage/README-CYAN.txt" <<EOF
MCL $version
============

Built from micans.org MCL 22-282 with cimfomfa/libtingea (21-361).

The package root is mcl/, so extracting into YR_MPE/bin/ yields
YR_MPE/bin/mcl/mcl(.exe). OrthoFinder invokes mcl by name; a launcher can
prepend this directory to PATH.

Example:
  mcl example.abc --abc -I 2.0 -o clusters.txt

Only the mcl executable is packaged. The optional mcx* utilities and RCL
scripts are not required by YR-MPE or OrthoFinder.

Licenses: LICENSE-MCL (GPL-3.0+) and LICENSE-CIMFOMFA (GPL-3.0+).
EOF

bash "$CYAN_ROOT/scripts/package_tool.sh" "$tool" "$stage"
